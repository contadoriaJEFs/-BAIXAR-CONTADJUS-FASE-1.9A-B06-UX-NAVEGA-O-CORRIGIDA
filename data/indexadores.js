function truncarParaBaixo10Casas(valor) {
    return Math.floor(valor * 10000000000) / 10000000000;
}

function calcularCoeficientePrevidMC2026(competencia, competenciaAtualizacao) {
    var indiceCompetencia = BASE_INDICE_PREVID_MC2026[competencia];
    var indiceAtualizacao = BASE_INDICE_PREVID_MC2026[competenciaAtualizacao];

    if (!indiceCompetencia) {
        throw new Error("Não há índice-base cadastrado para a competência " + competencia + ".");
    }

    if (!indiceAtualizacao) {
        throw new Error("Não há índice-base cadastrado para a atualização " + competenciaAtualizacao + ".");
    }

    return truncarParaBaixo10Casas(indiceAtualizacao / indiceCompetencia);
}
